def parsear_tag(col):
    tag = col.split('-')[-1].strip()
    m = re.match(r'^([A-Z]+)(\d*)([A-Z]?)$', tag)
    if not m:
        return None
    prefijo, digitos, sufijo = m.groups()
    sufijo = sufijo or None
    return (prefijo, digitos[-2:] if digitos else None, sufijo)


