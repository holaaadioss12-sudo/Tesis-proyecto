# 4b. ETIQUETA ALTERNATIVA POR TF·IDF SOBRE EVENTOS
# =============================================================================
# Esquema de ponderación de Alinezhad, Shang & Chen (2023), ecs. (6)-(8),
# aplicado sobre EVENTOS en vez de muestras:
#
#     W(r, f) = TF(r, f) · IDF(r)
#     TF(r, f) = eventos de la regla r en la ventana f / eventos totales de f
#     IDF(r)   = ln( N_ventanas / ventanas donde r aparece )
#
# El IDF castiga a las reglas ubicuas: una regla presente en el 95 % de las
# ventanas pesa ln(1/0,95) ~ 0,05; una presente en el 1 %, ln(100) ~ 4,6.
# Es una ponderación derivada SOLO de los datos -- sin tabla de criticidad
# experta, sin registros de mantenimiento, sin datos run-to-failure.
#
# Se omite el tercer factor del paper, el peso temporal TW = ln(tau_max/tau),
# porque tau se mide desde el inicio del EPISODIO detectado, y acá las
# ventanas son cortes fijos cada 600 s sin solape: el "inicio" no tiene
# significado físico. Para incorporarlo habría que segmentar por episodios
# con el criterio de tasa de alarmas de ANSI/ISA-18.2.
#
# ADVERTENCIA HONESTA: esto NO es criticidad por consecuencia. Mide
# especificidad diagnóstica -- qué regla informa más -- no qué falla cuesta
# más. Decirlo así en la tesis.
# =============================================================================
