"""
=============================================================================
PASO 05b — EL CRITERIO DEL UMBRAL
=============================================================================
Lo pidió el profesor en la reunión:

  "para calcular el umbral, qué es lo que se va a considerar bueno o malo,
   es considerar el error del bueno más tres veces la desviación estándar,
   por lo menos tres veces, es una recomendación, o bien el percentil 95
   también se usa"

Este script NO toca nada de lo que ya corriste. Solo lee el archivo de salida
del paso 05 y calcula los umbrales con los dos criterios que él nombró, más
una tercera variante robusta que conviene tener lista (ver la nota de abajo).

Entrada:  CR010_error_reconstruccion_W60.csv   (paso 05)
Salida:   05b_criterios_umbral.csv

POR QUÉ HAY UNA TERCERA VARIANTE
--------------------------------
La regla "media + 3 sigma" viene de la distribución normal: ahí cubre el
99,7 % de los casos. Pero el error de reconstrucción NO es normal, está
fuertemente sesgado a la derecha (mediana 0,0113, media 0,0176, máximo
0,1656 en las ventanas sanas). Con esa asimetría la media y la desviación se
inflan por la cola, y "media + 3 sigma" ya no equivale al 99,7 %.

La versión robusta de la misma idea usa mediana y MAD en vez de media y
desviación:

    umbral = mediana + k * 1.4826 * MAD

El factor 1,4826 hace que, SI los datos fueran normales, 1,4826*MAD coincida
con la desviación estándar. Así el criterio es el mismo, pero no se lo come
la cola. El script calcula las tres cosas y muestra a qué percentil equivale
cada una, que es la forma honesta de compararlas.
=============================================================================
"""

from google.colab import drive
drive.mount('/content/drive')
RUTA_BASE = '/content/drive/MyDrive/tesis_chancadores'

import numpy as np
import pandas as pd

W = 60
ARCHIVO_ERROR = f'{RUTA_BASE}/CR010_error_reconstruccion_W{W}.csv'
ARCHIVO_SALIDA = f'{RUTA_BASE}/05b_criterios_umbral.csv'

print('=' * 72)
print('05b — CRITERIOS PARA FIJAR EL UMBRAL')
print('=' * 72)

m = pd.read_csv(ARCHIVO_ERROR)
print(f'Ventanas evaluadas: {len(m):,}')

if 'es_normal' not in m.columns:
    raise SystemExit('Falta la columna es_normal. ¿Corriste el paso 05?')

nor = m.loc[m.es_normal, 'error_reconstruccion']
ano = m.loc[~m.es_normal, 'error_reconstruccion']
tot_graves = int((m.banda_severidad == '3_grave').sum())

print(f'  normales: {len(nor):,}   anómalas: {len(ano):,}   graves: {tot_graves:,}')


# =============================================================================
# 1. LA DISTRIBUCIÓN DE LAS NORMALES — es lo que decide qué criterio sirve
# =============================================================================
print('\n' + '=' * 72)
print('1. ¿CÓMO ES LA DISTRIBUCIÓN DEL ERROR EN LAS VENTANAS SANAS?')
print('=' * 72)

media = nor.mean()
desv = nor.std()
mediana = nor.median()
mad = (nor - mediana).abs().median()
mad_esc = 1.4826 * mad                       # equivalente robusto de sigma
asimetria = nor.skew()

print(f'  media    = {media:.5f}')
print(f'  mediana  = {mediana:.5f}')
print(f'  desv.est = {desv:.5f}')
print(f'  MAD      = {mad:.5f}   ->  1,4826*MAD = {mad_esc:.5f}')
print(f'  asimetría (skew) = {asimetria:.2f}')
print()
if asimetria > 1:
    print('  La asimetría es alta (> 1): la distribución NO es normal.')
    print('  Conviene reportar también la variante robusta por MAD, porque')
    print('  la desviación estándar está inflada por la cola derecha.')
else:
    print('  La asimetría es baja: media y desviación son representativas.')


# =============================================================================
# 2. LOS CRITERIOS
# =============================================================================
criterios = {}
for k in (1, 2, 3, 4):
    criterios[f'media + {k} sigma'] = media + k * desv
for k in (1, 2, 3, 4):
    criterios[f'mediana + {k} MAD (robusto)'] = mediana + k * mad_esc
for p in (90, 95, 97, 99):
    criterios[f'percentil {p}'] = float(np.percentile(nor, p))


def evaluar(umbral):
    """Qué pasa si se marca toda ventana con error por encima de este umbral."""
    marcada = m.error_reconstruccion > umbral
    tp = int((marcada & ~m.es_normal).sum())
    fp = int((marcada & m.es_normal).sum())
    fn = int((~marcada & ~m.es_normal).sum())
    gp = int((~marcada & (m.banda_severidad == '3_grave')).sum())
    return {
        'umbral': round(float(umbral), 5),
        'percentil_equivalente': round(float((nor <= umbral).mean() * 100), 1),
        'marcadas': int(marcada.sum()),
        'recall': round(tp / max(tp + fn, 1), 3),
        'precision': round(tp / max(tp + fp, 1), 3),
        'graves_perdidas': gp,
        'pct_graves_perdidas': round(100 * gp / max(tot_graves, 1), 1),
        'falsas_alarmas': fp,
        'pct_falsas': round(100 * fp / max(len(nor), 1), 1),
    }


filas = [{'criterio': nombre, **evaluar(u)} for nombre, u in criterios.items()]
tabla = pd.DataFrame(filas)

print('\n' + '=' * 72)
print('2. LOS CRITERIOS, LADO A LADO')
print('=' * 72)
print(tabla.to_string(index=False))

tabla.to_csv(ARCHIVO_SALIDA, sep=';', decimal=',', index=False, encoding='utf-8-sig')
print(f'\nGuardado: {ARCHIVO_SALIDA}')


