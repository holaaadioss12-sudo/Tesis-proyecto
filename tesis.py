# 3. LA LECTURA — esto es lo que hay que poder decir en voz alta
# =============================================================================
print('\n' + '=' * 72)
print('3. CÓMO SE LEE')
print('=' * 72)

u3s = criterios['media + 3 sigma']
u3m = criterios['mediana + 3 MAD (robusto)']
u95 = criterios['percentil 95']
p3s = (nor <= u3s).mean() * 100
p3m = (nor <= u3m).mean() * 100

print(f'  media + 3 sigma      = {u3s:.5f}  -> deja afuera el '
      f'{100 - p3s:.1f} % de las ventanas sanas (percentil {p3s:.1f})')
print(f'  mediana + 3 MAD      = {u3m:.5f}  -> deja afuera el '
      f'{100 - p3m:.1f} % (percentil {p3m:.1f})')
print(f'  percentil 95         = {u95:.5f}  -> deja afuera el 5,0 % por definición')
print()
print('  Si "media + 3 sigma" y "percentil 95" dan valores muy distintos, NO es')
print('  un error: es la asimetría. Los dos criterios responden a la misma idea')
print('  pero uno asume normalidad y el otro no asume nada.')

# La regla de decisión que conviene defender
mejor = tabla.loc[tabla.criterio == 'percentil 95'].iloc[0]
print()
print('  Punto de operación con el criterio que recomendó el profesor (P95):')
print(f'    umbral {mejor.umbral}  |  se pierde el {mejor.pct_graves_perdidas} % '
      f'de las ventanas graves  |  {mejor.pct_falsas} % de falsas alarmas')
print()
print('  Recordatorio para la defensa: una ventana grave que no se marca nunca')
